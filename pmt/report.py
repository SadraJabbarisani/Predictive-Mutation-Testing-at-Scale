"""Turn results/*.csv into figures, markdown tables and summary.json.

فارسی: ساخت جدول‌ها، نمودارها و summary.json از نتایج خام؛ اسلایدها اعدادشان را از همین فایل می‌خوانند.

No number is typed by hand: everything shown in the slides/README comes from
``results/summary.json`` produced here.
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

# fixed method -> colour mapping (colour follows the entity, never its rank)
COLORS = {"ace": "#eb6834", "random": "#2a78d6", "stratified": "#1baf7a", "selective": "#eda100",
          "pmt": "#6250d6", "seshat_lite": "#e87ba4", "model_only": "#008300", "active_topk": "#52514e"}
LABELS = {"ace": "ACE-MT (ours)", "random": "Random sampling", "stratified": "Stratified sampling",
          "selective": "Selective mutation", "pmt": "PMT (RF)", "seshat_lite": "Seshat-lite",
          "model_only": "Model only (calibrated)", "active_topk": "Active top-k"}
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"


def _style(ax, title, xlabel, ylabel):
    ax.set_title(title, loc="left", fontsize=11, color=INK)
    ax.set_xlabel(xlabel, color=MUTED)
    ax.set_ylabel(ylabel, color=MUTED)
    ax.grid(axis="y", color=GRID, lw=0.8)
    ax.spines[["top", "right"]].set_visible(False)
    ax.spines[["left", "bottom"]].set_color(GRID)
    ax.tick_params(colors=MUTED)


def _clean(o):
    """NaN/inf -> null so summary.json is strict JSON (readable from JavaScript)."""
    if isinstance(o, dict):
        return {k: _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, (float, np.floating)):
        return float(o) if np.isfinite(o) else None
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    return o


def md_table(df: pd.DataFrame, floatfmt=".3f") -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:{floatfmt}}" if isinstance(v, (float, np.floating)) else str(v)
                                     for v in r) + " |")
    return "\n".join(out)


def make_report(results_dir: str | Path) -> dict:
    R = Path(results_dir)
    fig_dir = R / "figures"
    fig_dir.mkdir(exist_ok=True, parents=True)
    summary: dict = {}
    md = ["# Results summary (auto-generated by `python -m pmt report`)\n"]

    rq1 = pd.read_csv(R / "rq1_prediction.csv") if (R / "rq1_prediction.csv").exists() else None
    if rq1 is not None:
        t = (rq1[rq1["scope"] == "covered"].groupby(["setting", "model"])[["precision", "recall", "mcc", "auc",
                                                                           "brier", "ece"]].mean().reset_index())
        summary["rq1"] = t.round(4).to_dict(orient="records")
        md += ["## RQ1 - prediction quality (covered mutants, mean over projects)\n", md_table(t), ""]

    rq2 = pd.read_csv(R / "rq2_estimates.csv") if (R / "rq2_estimates.csv").exists() else None
    if rq2 is not None:
        r = rq2[rq2["method"] != "full"]
        t = (r.groupby(["setting", "budget", "method"]).agg(mae=("abs_err", "mean"), ci_coverage=("covers", "mean"),
                                                            ci_width=("ci_width", "mean"),
                                                            exec_frac=("exec_frac", "mean")).reset_index())
        summary["rq2"] = t.round(4).to_dict(orient="records")
        o = (r.groupby(["budget", "method"]).agg(mae=("abs_err", "mean"), ci_coverage=("covers", "mean"),
                                                 ci_width=("ci_width", "mean")).reset_index())
        summary["rq2_overall"] = o.round(4).to_dict(orient="records")
        summary["dataset"] = dict(projects=int(rq2["project"].nunique()), mutants=int(
            rq2[rq2["method"] == "full"]["N"].sum()),
            per_project=rq2[rq2["method"] == "full"][["project", "setting", "N", "true", "exec_frac"]]
            .rename(columns={"true": "score", "exec_frac": "covered_frac"}).round(4).to_dict(orient="records"))
        md += ["## RQ2 - mean absolute error of the estimated mutation score\n",
               md_table(t.pivot_table(index=["setting", "budget"], columns="method", values="mae").reset_index()), "",
               "### CI coverage (target 0.95)\n",
               md_table(t.dropna(subset=["ci_coverage"]).pivot_table(index=["setting", "budget"], columns="method",
                                                                     values="ci_coverage").reset_index()), ""]
        settings = list(r["setting"].unique())
        fig, axes = plt.subplots(1, len(settings), figsize=(5.2 * len(settings), 3.8), sharey=True, squeeze=False)
        for ax, st in zip(axes[0], settings):
            g = t[t["setting"] == st]
            for m in [m for m in COLORS if m in g["method"].unique()]:
                gg = g[g["method"] == m].sort_values("budget")
                lw = 2.6 if m == "ace" else 1.6
                ax.plot(gg["budget"] * 100, gg["mae"], marker="o", ms=5, lw=lw, color=COLORS[m],
                        label=LABELS.get(m, m), zorder=3 if m == "ace" else 2)
            _style(ax, f"{st}", "budget (% of mutants executed)", "MAE of mutation score")
            ax.set_xticks(sorted(g["budget"].unique() * 100))
        axes[0][-1].legend(frameon=False, fontsize=8, loc="upper right")
        fig.tight_layout()
        fig.savefig(fig_dir / "rq2_error_vs_budget.png", dpi=200)
        plt.close(fig)
        if (R / "rq2_stats.csv").exists():
            s = pd.read_csv(R / "rq2_stats.csv")
            summary["rq2_stats"] = s.round(4).to_dict(orient="records")
            md += ["### ACE-MT vs. each baseline (Wilcoxon signed-rank, Vargha-Delaney A12; A12<0.5 = ours better)\n",
                   md_table(s), ""]

    if (R / "rq3_cost.csv").exists():
        c = pd.read_csv(R / "rq3_cost.csv")
        summary["rq3"] = c.round(4).to_dict(orient="records")
        md += ["## RQ3 - cost\n", md_table(c), ""]

    if (R / "rq4_ranking.csv").exists():
        k = pd.read_csv(R / "rq4_ranking.csv")
        t = k.groupby("method").agg(kendall_tau=("kendall_tau", "mean"), mae=("mae", "mean")).reset_index()
        summary["rq4"] = t.round(4).to_dict(orient="records")
        md += ["## RQ4 - ranking random sub-suites by estimated score (Kendall tau, mean over projects)\n",
               md_table(t), ""]

    if (R / "rq5_ablation.csv").exists():
        a = pd.read_csv(R / "rq5_ablation.csv")
        f = (a[(a["kind"] == "features") & (a["method"] == "ace")].groupby("variant")
             .agg(mae=("abs_err", "mean"), auc=("auc", "mean")).reset_index())
        p = (a[a["kind"] == "policy"].groupby("variant").agg(mae=("abs_err", "mean"), ci_coverage=("covers", "mean"))
             .reset_index().sort_values("mae"))
        summary["rq5_features"] = f.round(4).to_dict(orient="records")
        summary["rq5_policies"] = p.round(4).to_dict(orient="records")
        md += ["## RQ5 - ablation: feature groups (ACE-MT MAE at 10 % budget, model AUC)\n", md_table(f), "",
               "## RQ5 - ablation: components of ACE-MT\n", md_table(p), ""]
        fig, ax = plt.subplots(figsize=(6.4, 3.6))
        cols = ["#eb6834" if v == "ace (default)" else "#9b9a95" for v in p["variant"]]
        ax.barh(p["variant"], p["mae"], color=cols, height=0.6)
        ax.invert_yaxis()
        _style(ax, "ACE-MT components (MAE, budget 10 %)", "MAE", "")
        ax.grid(axis="x", color=GRID)
        ax.grid(axis="y", visible=False)
        fig.tight_layout()
        fig.savefig(fig_dir / "rq5_ablation.png", dpi=200)
        plt.close(fig)

    (R / "summary.json").write_text(json.dumps(_clean(summary), indent=2, allow_nan=False))
    (R / "summary.md").write_text("\n".join(md))
    return summary
